# -*- coding: utf-8 -*-
r"""Export the prototype's page chrome (SVG sprite, header, footer + dialogs) as HTML fragments for pressmedia_laravel.

The chrome is generated by build_site.py and is the same on every page; copying it keeps the Laravel site
identical to the prototype without hand-porting ~40 KB of markup. Relative links are made root-absolute
(Laravel URLs mirror the prototype: /fr/..., /assets/...). Per-page parts become %%MARKERS%% that
App\Support\Chrome fills at render time: the language switch targets and the top-bar date. Plain HTML, not
Blade, so ~40 KB of markup is never parsed by the template engine. Re-run after changing the prototype:
    python tools/export_chrome.py
Known limit: the mega-menu cards and the ticker are a snapshot of the latest posts at export time.
"""
import posixpath
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROTO = ROOT / "prototype_html"
OUT = ROOT / "pressmedia_laravel" / "resources" / "chrome"
SKIP = ("http:", "https:", "#", "/", "mailto:", "tel:", "data:", "javascript:", "{")


def absolutize(html, page_url):
    base = posixpath.dirname(page_url)

    def one(v):
        v = v.strip()
        if not v or v.startswith(SKIP):
            return v
        path, _, frag = v.partition("#")
        return posixpath.normpath(posixpath.join(base, path)) + ("#" + frag if frag else "")

    def attr(m):
        name, val = m.group(1), m.group(2)
        if name in ("srcset", "imagesrcset"):
            val = ", ".join(" ".join([one(p.strip().split(" ")[0])] + p.strip().split(" ")[1:]) for p in val.split(","))
        else:
            val = one(val)
        return f'{name}="{val}"'

    return re.sub(r'\b(href|src|srcset|imagesrcset|action|poster|data-src|data-href)="([^"]*)"', attr, html)


def markers(html):
    """Swap the per-page parts for markers filled by App\\Support\\Chrome."""
    def switch(m):
        return re.sub(r'href="[^"]*"(\s+hreflang="(fr|en)")', lambda a: f'href="%%ALT_{a.group(2).upper()}%%"' + a.group(1), m.group(0))
    html = re.sub(r'<ul class="lang-switch[^"]*"[^>]*>.*?</ul>', switch, html, flags=re.S)
    html = re.sub(r'(<p class="topbar-date"[^>]*>)[^<]*(</p>)', r'\1%%DATE%%\2', html)
    return "<!-- Generated by tools/export_chrome.py from the prototype. Do not edit by hand. -->\n" + html + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for lang in ("fr", "en"):
        page = sorted((PROTO / lang / "articles").glob("*.html"))[0]
        url = f"/{lang}/articles/{page.name}"
        s = page.read_text(encoding="utf8")
        body = s.index("<body")
        sprite_a = s.index("<svg", body)
        sprite = s[sprite_a:s.index("</svg>", sprite_a) + 6]
        header = s[s.index('<header class="site-header"'):s.index("</header>") + 9]
        foot_a = s.index('<footer class="site-footer"')
        footer = s[foot_a:s.index('<script src="', foot_a)]
        if lang == "fr":
            (OUT / "sprite.html").write_text(sprite + "\n", encoding="utf8")
        for name, part in (("header", header), ("footer", footer)):
            (OUT / f"{name}-{lang}.html").write_text(markers(absolutize(part, url)), encoding="utf8")
        print(lang, "header", len(header), "footer", len(footer))


def home_static():
    """Static blocks closing the home page (search frame, wave, editorial, tiles), same per language."""
    import sys
    sys.argv = sys.argv[:1]
    import build_site as B
    for lang in ("fr", "en"):
        B.begin(lang, f"{lang}/index.html", {})
        html = B.search_block("q-home") + B.WAVE + B.editorial_block() + B.tiles_block()
        (OUT / f"home-static-{lang}.html").write_text(markers(absolutize(html, f"/{lang}/index.html")), encoding="utf8")
        print(lang, "home static", len(html))


if __name__ == "__main__":
    main()
    home_static()
