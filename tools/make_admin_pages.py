#!/usr/bin/env python3
"""Admin scaffolding for the module pages added on 2026-10-28 (Analytics, Tags, Videos, Magazine, Radios, Television, Audit log, Backups)
and the seed file for the four channel modules. Re-runnable: pages are rewritten from admin/podcasts.html, the seed from data/*.json.
Usage: python tools/make_admin_pages.py"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROTO = ROOT / "prototype_html"
ADMIN = PROTO / "admin"
DATA = PROTO / "data"

SEED = {"videos": ("AGP_VIDEOS", "videos.json"), "magazine": ("AGP_MAGAZINE", "magazine.json"), "radios": ("AGP_RADIOS", "radios.json"), "television": ("AGP_TV", "tv.json")}
PAGES = {  # page -> (title, extra scripts after admin-lib.js)
    "analytics": ("Analytics", ["admin-stats.js", "admin-analytics.js"]),
    "tags": ("Tags", ["admin-tags.js"]),
    "videos": ("Videos", ["admin-directories.js"]),
    "magazine": ("Magazine", ["admin-directories.js"]),
    "radios": ("African radios", ["admin-directories.js"]),
    "television": ("African television", ["admin-directories.js"]),
    "audit": ("Audit log", ["admin-audit.js"]),
    "backups": ("Backups", ["admin-backups.js"]),
}

tpl = (ADMIN / "podcasts.html").read_text(encoding="utf8")
for page, (title, extra) in PAGES.items():
    html = re.sub(r"<title>.*?</title>", f"<title>{title} - AGP Admin</title>", tpl)
    html = html.replace('data-page="podcasts"', f'data-page="{page}"')
    scripts = ['<script src="data-seed.js" defer></script>']
    if page in SEED:
        scripts.append('<script src="directories-seed.js" defer></script>')
    scripts += ['<script src="../assets/js/admin.js" defer></script>', '<script src="../assets/js/admin-lib.js" defer></script>'] + [f'<script src="../assets/js/{s}" defer></script>' for s in extra]
    html = re.sub(r'<script src="data-seed\.js" defer></script>.*?(?=</body>)', "\n".join(scripts) + "\n", html, flags=re.S)
    (ADMIN / f"{page}.html").write_text(html, encoding="utf8")

# dashboard and ads read the synthetic statistics: load admin-stats.js after admin-lib.js
for page in ("index", "ads"):
    p = ADMIN / f"{page}.html"
    h = p.read_text(encoding="utf8")
    if "admin-stats.js" not in h:
        h = h.replace('<script src="../assets/js/admin-lib.js" defer></script>', '<script src="../assets/js/admin-lib.js" defer></script>\n<script src="../assets/js/admin-stats.js" defer></script>')
        p.write_text(h, encoding="utf8")

# seed for the channel modules = copies of the public data files
out = ["/* Generated by tools/make_admin_pages.py from data/*.json. Do not edit by hand: edit the data file or use the console and Export JSON. */"]
for page, (var, f) in SEED.items():
    src = DATA / f
    out.append(f"window.{var} = {json.dumps(json.loads(src.read_text(encoding='utf8')), ensure_ascii=False)};" if src.exists() else f"window.{var} = null;")
(ADMIN / "directories-seed.js").write_text("\n".join(out) + "\n", encoding="utf8")
print("pages:", ", ".join(PAGES), "| seed:", ", ".join(f for _, f in SEED.values()))
